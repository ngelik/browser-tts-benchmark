#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cache = path.resolve(process.env.AUDIO_CPP_CACHE ?? path.join(root, '.cache/nov14'));
const source = path.join(cache, 'audio-cpp');
const emsdk = path.join(cache, 'emsdk');
const outputDefault = path.join(cache, 'release/THIRD-PARTY-NOTICES.txt');
const sourcePin = 'd38518a0d6a7aaab9d3f3dd91e9780c69857b0ac';
const emscriptenPin = '708dcbcc9ee23bc7d2dad44fc90db377e38b771c';
const emscriptenVersion = '6.0.13';
const dawnRevision = '31e25af254ab572c77054edec4946d2244e184dd';

const entries = [
  ['audio.cpp — Apache-2.0', 'audio-cpp/LICENSE'],
  ['GGML — MIT', 'audio-cpp/external/ggml/LICENSE'],
  ['SentencePiece — Apache-2.0', 'audio-cpp/external/sentencepiece/LICENSE'],
  ['Protocol Buffers lite (SentencePiece bundled copy) — BSD-3-Clause and Apache-2.0', 'audio-cpp/external/sentencepiece/third_party/protobuf-lite/LICENSE'],
  ['Abseil (SentencePiece bundled copy) — Apache-2.0', 'audio-cpp/external/sentencepiece/third_party/absl/LICENSE'],
  ['Darts Clone (SentencePiece bundled copy) — BSD-3-Clause', 'audio-cpp/external/sentencepiece/third_party/darts_clone/LICENSE'],
  ['Emscripten — MIT and University of Illinois/NCSA', 'emsdk/upstream/emscripten/LICENSE'],
  ['Dawn WebGPU C bindings — BSD-3-Clause', 'emsdk/upstream/emscripten/cache/ports/emdawnwebgpu/emdawnwebgpu_pkg/webgpu/src/LICENSE'],
  ['Dawn WebGPU C++ bindings — BSD-3-Clause', 'emsdk/upstream/emscripten/cache/ports/emdawnwebgpu/emdawnwebgpu_pkg/webgpu_cpp/LICENSE'],
  ['cJSON — MIT', 'audio-cpp/external/cJSON/LICENSE'],
  ['LibYAML — MIT', 'audio-cpp/external/libyaml/License'],
  ['LZ4 — BSD-2-Clause', 'audio-cpp/external/lz4/LICENSE'],
  ['utf8proc — MIT', 'audio-cpp/external/utf8proc/LICENSE.md'],
];

function gitHead(cwd) {
  const result = spawnSync('git', ['-C', cwd, 'rev-parse', 'HEAD'], { encoding: 'utf8' });
  if (result.status !== 0) throw new Error(`Cannot identify pinned source at ${cwd}`);
  return result.stdout.trim();
}

let check = false;
let outputArg = null;
for (let index = 2; index < process.argv.length; index += 1) {
  const arg = process.argv[index];
  if (arg === '--check') {
    check = true;
  } else if (arg === '--out' && process.argv[index + 1]) {
    outputArg = process.argv[index + 1];
    index += 1;
  } else {
    throw new Error('Usage: node tools/build-audio-cpp-notices.mjs [--check] [--out FILE]');
  }
}
if (gitHead(source) !== sourcePin) throw new Error(`audio.cpp source must be ${sourcePin}`);
if (gitHead(emsdk) !== emscriptenPin) throw new Error(`Emscripten source must be ${emscriptenPin}`);
const version = (await readFile(path.join(emsdk, 'upstream/emscripten/emscripten-version.txt'), 'utf8')).trim().replaceAll('"', '');
if (version !== emscriptenVersion) throw new Error(`Expected Emscripten ${emscriptenVersion}, found ${version}`);
const dawnVersionPath = path.join(emsdk, 'upstream/emscripten/cache/ports/emdawnwebgpu/emdawnwebgpu_pkg/VERSION.txt');
const dawnVersion = await readFile(dawnVersionPath, 'utf8');
if (!dawnVersion.includes(dawnRevision)) throw new Error(`Expected Dawn revision ${dawnRevision}`);

const parts = [
  'Browser TTS Benchmark audio.cpp WebAssembly runtime — third-party notices',
  '',
  'This file is generated by tools/build-audio-cpp-notices.mjs from the pinned source license files listed below.',
  'It covers the distributed bench_browser.js and bench_browser.wasm runtime, including its compiled WebGPU bindings.',
  'The GGUF model files and voice/model terms are separate; see docs/LICENSING.md and the model-specific support notes.',
  'To reproduce this notice, use the pinned sources below and run: node tools/build-audio-cpp-notices.mjs',
  '',
  `audio.cpp source: 0xShug0/audio.cpp ${sourcePin}`,
  `Emscripten source: emsdk ${emscriptenVersion}, commit ${emscriptenPin}`,
  `Dawn source revision: ${dawnRevision}`,
  '',
];

for (const [heading, relativePath] of entries) {
  const filename = path.join(cache, relativePath);
  const bytes = await readFile(filename);
  const body = bytes.toString('utf8').replaceAll('\r\n', '\n').replace(/\n+$/u, '');
  const digest = createHash('sha256').update(bytes).digest('hex');
  parts.push(`\n${'='.repeat(78)}\n${heading}\nSource: ${relativePath}\nSHA-256: ${digest}\n${'='.repeat(78)}\n\n${body}\n`);
}
const result = `${parts.join('\n').replace(/\n+$/u, '')}\n`;
const output = path.resolve(outputArg ?? outputDefault);
if (check) {
  const existing = await readFile(output, 'utf8');
  if (existing !== result) throw new Error(`Third-party notice differs from generated output: ${output}`);
  console.log(`Notice verified: ${output} (${createHash('sha256').update(existing).digest('hex')})`);
} else {
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, result);
  console.log(`Notice written: ${output} (${createHash('sha256').update(result).digest('hex')})`);
}
